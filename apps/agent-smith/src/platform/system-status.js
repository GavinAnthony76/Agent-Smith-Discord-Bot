import { TARGET_GUILD_ID } from '../config.js';
import { recentFailures } from './diagnostics.js';
import { historicalGuild } from './guild-lifecycle.js';
import { subsystemObservation } from '../operational-health.js';

export function createSystemStatus({pool,discord,env,legacyActions}) {
  return async authority=>{
    const id=authority.guild.id,components=[];
    const component=(key,label,status,detail,durationMs)=>components.push({key,label,status,detail,
      ...(durationMs===undefined?{}:{durationMs})});
    const connected=discord.client?.isReady?.()===true;
    const archived=historicalGuild(id);
    component('worker','Agent Smith Worker',env.NODE_ENV==='production'?'HEALTHY':'UNKNOWN',
      env.NODE_ENV==='production'?'This response is served by the running management worker.':'Preview process, not production worker evidence.');
    component('gateway','Discord Gateway',archived?'DISABLED':connected?'HEALTHY':'UNKNOWN',
      archived?'Historical guild; no runtime dispatch.':connected?'Existing client is connected.':'No connected production Gateway observed here.');
    const start=performance.now();
    let database=true;
    try {await pool.query('SELECT 1');}
    catch {database=false;}
    component('database','Database',database?'HEALTHY':'ERROR',
      database?'Read query completed.':'Database could not be reached.',performance.now()-start);
    component('guild','Selected Guild',archived?'DISABLED':authority.installed?'HEALTHY':'UNKNOWN',
      archived?'Historical/reference-only; activation is refused.':'Fresh authorization verified for this request.');
    try {
      // Health exposes a bounded summary, not the Owner-only setup journal.
      const row=(await pool.query(`SELECT r.data->>'state' AS state,g.setup_complete
        FROM platform_guilds g LEFT JOIN platform_records r ON r.guild_id=g.guild_id
          AND r.collection='system-setup' AND r.record_id='setup-lifecycle'
        WHERE g.guild_id=$1`,[id])).rows[0];
      const state=row?.state??(row?.setup_complete?'VERIFYING':'NOT_CONFIGURED');
      component('setup','Setup State',state==='READY'?'HEALTHY':state==='FAILED'?'ERROR':'DEGRADED',
        `${state}. Configuration readiness is not subsystem health.`);
    } catch {component('setup','Setup State','UNKNOWN','Saved setup state is unavailable.');}
    const native=id===TARGET_GUILD_ID;
    component('moderation','Moderation','UNKNOWN',
      native && !!legacyActions(id)?.cases?'Guarded native adapter is available; no moderation action was exercised.':'No observed moderation operation.');
    for(const [key,label] of [['onboarding','Onboarding'],['progression','Progression'],['feeds','Feeds']]) {
      const observed=subsystemObservation(id,key);
      component(key,label,archived?'DISABLED':observed.status,
        archived?'No actions are dispatched for this historical guild.':observed.detail);
    }
    component('ai','AI',archived || env.AI_ENABLED==='false'?'DISABLED':'UNKNOWN',
      'No provider request is generated by this status check.');
    const tick=subsystemObservation(id,'background');
    component('background','Background Workers',archived?'DISABLED':tick.status,
      archived?'No historical guild jobs are activated.':tick.detail);
    return {checkedAt:new Date().toISOString(),lastHeartbeat:tick.at,
      components,recentErrors:recentFailures(id)};
  };
}
